/**
 * WHO 儿童生长标准（0-24 月龄）近似百分位数据，仅供参考。
 * 数组下标 = 月龄（0-24）。P15/P85 由 P3/P50/P97 按正态近似推算。
 */

export interface PercentileCurves {
  p3: number[]
  p15: number[]
  p50: number[]
  p85: number[]
  p97: number[]
}

// z(P3)≈-1.881, z(P15)≈-1.036 → 比例约 0.551
const K = 0.551

function derive(p3: number[], p50: number[], p97: number[]): PercentileCurves {
  const p15 = p50.map((v, i) => +(v + K * (p3[i] - v)).toFixed(2))
  const p85 = p50.map((v, i) => +(v + K * (p97[i] - v)).toFixed(2))
  return { p3, p15, p50, p85, p97 }
}

